export const buildUserPrompt = (text: string, knowledge: string | null, requester: string) => {
  const context = [`현재 시각: ${formatCurrentTime()} (Asia/Seoul)`, `요청자: ${requester}`];
  if (knowledge) {
    context.push('', knowledge);
  }

  return `<context>\n${context.join('\n')}\n</context>\n\n${text}`;
};
